static void test_gradient(uint16_t *buf, esp_lcd_panel_handle_t panel)
{
    ESP_LOGI(TAG, "--- Test 5: Gradient ---");

    for (int y = 0; y < LCD_H; y++) {
        for (int x = 0; x < LCD_W; x++) {
            uint8_t r = (uint8_t)(x * 255 / LCD_W);
            uint8_t g = (uint8_t)(y * 255 / LCD_H);
            uint8_t b = (uint8_t)((x + y) * 255 / (LCD_W + LCD_H));
            buf[y * LCD_W + x] = rgb565(r, g, b);
        }
    }
    esp_lcd_panel_draw_bitmap(panel, 0, 0, LCD_W, LCD_H, buf);
    vTaskDelay(pdMS_TO_TICKS(2000));
}

/* ========================================================================
 * Main Entry
 * ======================================================================== */

void app_main(void)
{
    ESP_LOGI(TAG, "");
    ESP_LOGI(TAG, "======================================================");
    ESP_LOGI(TAG, "  Leisound V1 — ST7789V TFT LCD Display Test");
    ESP_LOGI(TAG, "  Driver: esp_lcd_panel_st7789 | ESP-IDF");
    ESP_LOGI(TAG, "======================================================");

    /* --- 1. Power on --- */
    board_power_on();

    /* --- 2. Hardware reset --- */
    lcd_hw_reset();

    /* --- 3. Initialize SPI bus --- */
    ESP_LOGI(TAG, "--- SPI Bus Init ---");
    spi_bus_config_t spi_bus_cfg = {
        .mosi_io_num = PIN_SPI_MOSI,
        .miso_io_num = PIN_SPI_MISO,
        .sclk_io_num = PIN_SPI_SCK,
        .quadwp_io_num = -1,
        .quadhd_io_num = -1,
        .max_transfer_sz = LCD_BUF_SIZE + 16,
    };
    ESP_ERROR_CHECK(spi_bus_initialize(SPI_HOST_ID, &spi_bus_cfg, SPI_DMA_CH_AUTO));

    /* --- 4. Create panel IO (SPI + DC line) --- */
    ESP_LOGI(TAG, "--- Panel IO Init ---");
    esp_lcd_panel_io_spi_config_t io_cfg = {
        .cs_gpio_num = PIN_LCD_CS,
        .dc_gpio_num = PIN_LCD_DC,
        .spi_mode = 0,
        .pclk_hz = SPI_FREQ_HZ,
        .trans_queue_depth = 10,
        .lcd_cmd_bits = 8,
        .lcd_param_bits = 8,
    };
    esp_lcd_panel_io_handle_t io_handle = NULL;
    ESP_ERROR_CHECK(esp_lcd_new_panel_io_spi((esp_lcd_spi_bus_handle_t)SPI_HOST_ID,
                                              &io_cfg, &io_handle));

    /* --- 5. Create ST7789 panel --- */
    ESP_LOGI(TAG, "--- ST7789 Panel Init ---");
    esp_lcd_panel_dev_config_t panel_cfg = {
        .reset_gpio_num = PIN_LCD_RST,
        .rgb_ele_order = LCD_RGB_ELEMENT_ORDER_RGB,
        .bits_per_pixel = 16,
    };
    esp_lcd_panel_handle_t panel_handle = NULL;
    ESP_ERROR_CHECK(esp_lcd_new_panel_st7789(io_handle, &panel_cfg, &panel_handle));

    /* --- 6. Reset, init, turn on --- */
    ESP_ERROR_CHECK(esp_lcd_panel_reset(panel_handle));
    ESP_ERROR_CHECK(esp_lcd_panel_init(panel_handle));
    ESP_ERROR_CHECK(esp_lcd_panel_invert_color(panel_handle, true));
    ESP_ERROR_CHECK(esp_lcd_panel_disp_on_off(panel_handle, true));
    ESP_LOGI(TAG, "  ST7789V ready — 240x320 RGB565");

    /* --- 7. Allocate frame buffer --- */
    uint16_t *fb = heap_caps_malloc(LCD_BUF_SIZE, MALLOC_CAP_SPIRAM | MALLOC_CAP_8BIT);
    if (!fb) {
        fb = heap_caps_malloc(LCD_BUF_SIZE, MALLOC_CAP_INTERNAL | MALLOC_CAP_8BIT);
    }
    if (!fb) {
        ESP_LOGE(TAG, "FATAL: cannot allocate frame buffer!");
        goto fail;
    }
    ESP_LOGI(TAG, "  Frame buffer: %d bytes @ %p", LCD_BUF_SIZE, fb);

    /* --- 8. Run tests --- */
    ESP_LOGI(TAG, "");
    ESP_LOGI(TAG, "======================================================");
    ESP_LOGI(TAG, "  Starting visual tests...");
    ESP_LOGI(TAG, "======================================================");

    test_fill_colors(fb, panel_handle);
    test_color_bars(fb, panel_handle);
    test_rectangles(fb, panel_handle);
    test_text_card(fb, panel_handle);
    test_gradient(fb, panel_handle);

    /* --- Done --- */
    ESP_LOGI(TAG, "");
    ESP_LOGI(TAG, "======================================================");
    ESP_LOGI(TAG, "  ALL DISPLAY TESTS COMPLETE");
    ESP_LOGI(TAG, "======================================================");
    ESP_LOGI(TAG, "  Summary:");
    ESP_LOGI(TAG, "    1. Solid Colors  — R, G, B, W, Black");
    ESP_LOGI(TAG, "    2. Color Bars    — 8 vertical bars");
    ESP_LOGI(TAG, "    3. Rectangles    — nested colored borders");
    ESP_LOGI(TAG, "    4. Text Card     — full info screen");
    ESP_LOGI(TAG, "    5. Gradient      — RGB gradient fill");

    while (1) {
        vTaskDelay(pdMS_TO_TICKS(5000));
        ESP_LOGI(TAG, "STATUS: DISPLAY TEST PASSED");
    }

fail:
    ESP_LOGE(TAG, "DISPLAY TEST FAILED");
    while (1) { vTaskDelay(pdMS_TO_TICKS(1000)); }
}
