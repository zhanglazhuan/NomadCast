static void test_fill_colors(uint16_t *buf, esp_lcd_panel_handle_t panel)
{
    ESP_LOGI(TAG, "--- Test 1: Solid Colors ---");

    uint16_t colors[] = { COLOR_RED, COLOR_GREEN, COLOR_BLUE, COLOR_WHITE, COLOR_BLACK };
    const char *names[] = { "RED", "GREEN", "BLUE", "WHITE", "BLACK" };

    for (int i = 0; i < 5; i++) {
        ESP_LOGI(TAG, "  %s", names[i]);
        fill_screen(buf, colors[i]);
        esp_lcd_panel_draw_bitmap(panel, 0, 0, LCD_W, LCD_H, buf);
        vTaskDelay(pdMS_TO_TICKS(800));
    }
}

static void test_color_bars(uint16_t *buf, esp_lcd_panel_handle_t panel)
{
    ESP_LOGI(TAG, "--- Test 2: Color Bars ---");

    uint16_t colors[] = {
        COLOR_RED, COLOR_GREEN, COLOR_BLUE, COLOR_YELLOW,
        COLOR_CYAN, COLOR_MAGENTA, COLOR_WHITE, COLOR_BLACK
    };
    int bar_w = LCD_W / 8;

    for (int i = 0; i < 8; i++) {
        fill_rect(buf, i * bar_w, 0, bar_w, LCD_H, colors[i]);
    }
    esp_lcd_panel_draw_bitmap(panel, 0, 0, LCD_W, LCD_H, buf);
    vTaskDelay(pdMS_TO_TICKS(1500));
}

static void test_rectangles(uint16_t *buf, esp_lcd_panel_handle_t panel)
{
    ESP_LOGI(TAG, "--- Test 3: Rectangles ---");
    fill_screen(buf, COLOR_BLACK);

    /* Nested colored rectangles */
    uint16_t colors[] = { COLOR_RED, COLOR_GREEN, COLOR_BLUE, COLOR_YELLOW,
                          COLOR_CYAN, COLOR_MAGENTA, COLOR_WHITE };
    int margin = 4;
    for (int i = 0; i < 7; i++) {
        int x = margin * i, y = margin * i;
        int w = LCD_W - 2 * margin * i, h = LCD_H - 2 * margin * i;
        draw_rect(buf, x, y, w, h, colors[i]);
    }
    esp_lcd_panel_draw_bitmap(panel, 0, 0, LCD_W, LCD_H, buf);
    vTaskDelay(pdMS_TO_TICKS(1500));
}

