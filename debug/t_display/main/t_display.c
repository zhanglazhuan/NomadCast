static const uint8_t *font_get_glyph(char c)
{
    if (c < 32 || c > 126) c = '?';
    return &_font_data_8x16[(c - 32) * FONT_H];
}

static void draw_char(uint16_t *buf, int x, int y, char c, uint16_t fg, uint16_t bg)
{
    const uint8_t *glyph = font_get_glyph(c);
    for (int row = 0; row < FONT_H; row++) {
        uint8_t line = glyph[row];
        for (int col = 0; col < FONT_W; col++) {
            int px = x + col, py = y + row;
            if (px < 0 || px >= LCD_W || py < 0 || py >= LCD_H) continue;
            buf[py * LCD_W + px] = (line & (0x80 >> col)) ? fg : bg;
        }
    }
}

static void draw_string(uint16_t *buf, int x, int y, const char *str, uint16_t fg, uint16_t bg)
{
    int cx = x, cy = y;
    while (*str) {
        if (*str == '\n') { cx = x; cy += FONT_H; }
        else { draw_char(buf, cx, cy, *str, fg, bg); cx += FONT_W; }
        str++;
    }
}

